async def _allow_agent_execution(env: dict[str, Any], company_id: Any) -> None:
    for agent in await env["agents_repo"].list_for_company(company_id):
        await env["permissions"].set_policy(
            env["owner"],
            env["org"],
            company_id,
            principal_type="agent",
            principal_id=str(agent.id),
            resource_type="task",
            resource_id=None,
            action="execute",
            decision=PermissionDecision.ALLOW,
        )


async def _idea_to_company(env: dict[str, Any]) -> tuple[Any, Any, Any, Any]:
    """Submit -> blueprint -> bootstrap -> CEO -> initial plan."""
    idea = await env["idea_service"].submit_idea(
        env["owner"], env["org"], raw_idea=IDEA, target_market="independent music teachers"
    )
    idea = await env["blueprint_service"].generate_blueprint(
        env["owner"], env["org"], idea.id, env["idea_service"], context={}
    )
    outcome = await env["bootstrap_service"].bootstrap_company(env["owner"], env["org"], idea.id)
    ceo = await env["ceo_service"].initialize_ceo(
        env["owner"], env["org"], outcome.company_id, idea.id
    )
    plan = await env["ceo_service"].generate_initial_plan(
        env["owner"], env["org"], outcome.company_id, idea.id
    )
    _ = ceo
    return idea, outcome, plan, outcome.company


class TestSixteenStepWorkflow:
    async def test_from_idea_to_verified_execution_and_observation(
        self, stack: Any, tmp_path: Any
    ) -> None:
        runtime = _build_runtime(
            [
                _tool_echo("bootstrap evidence"),
                _final({"output": {"echo": "bootstrap evidence"}, "summary": "evidence read"}),
            ],
            tmp_path,
        )
        env = stack(runtime)
        owner, org = env["owner"], env["org"]

        # 1. Authenticated ownership: the owner is a member; the rival is not.
        assert owner.email == "owner@example.com"
        with pytest.raises(NotAMember):
            await env["idea_service"].list_ideas(env["rival"], org)

        # 2. Submit the idea: exact text preserved, intake validated.
        idea = await env["idea_service"].submit_idea(
            owner,
            org,
            raw_idea=IDEA,
            target_market="independent music teachers",
            idempotency_key="e2e-idea-1",
        )
        assert idea.raw_idea == IDEA
        assert idea.description == IDEA
        assert idea.intake_status is IntakeStatus.VALIDATED
        assert idea.blueprint is None

        # 3. Generate the blueprint (generation ends with artifact verification).
        idea = await env["blueprint_service"].generate_blueprint(
            owner, org, idea.id, env["idea_service"], context={}
        )
        assert idea.blueprint is not None
        assert idea.blueprint_version == 1
        assert idea.blueprint_status is BlueprintStatus.VALIDATED

        # 4. Independent artifact verification of the persisted payload.
        from polsia.core.business.entities import blueprint_from_dict

        artifact = blueprint_from_dict(idea.id, idea.organization_id, idea.blueprint or {})
        artifact.validate()
        verification = env["verifier"].verify_blueprint_artifact(artifact, persisted=idea)
        assert verification.passed, verification.reason
        revalidated = await env["blueprint_service"].validate_blueprint(owner, org, idea.id)
        assert revalidated.blueprint_status is BlueprintStatus.VALIDATED

        # 5. Bootstrap the company.
        outcome = await env["bootstrap_service"].bootstrap_company(owner, org, idea.id)
        company = outcome.company
        assert outcome.reused is False
        assert company.organization_id == org
        assert company.strategy["bootstrap_idea_id"] == str(idea.id)
        assert company.strategy["planning_readiness"]["ready_for_initial_plan"] is True
        assert len(outcome.goals) == len(artifact.initial_goals)
        assert len(outcome.kpis) == len(artifact.initial_kpis)
        assert len(outcome.agents) == len(artifact.proposed_agent_roster)
        assert outcome.memory_record_ids

        # 6. CEO initialization from trusted company state.
        ceo = await env["ceo_service"].initialize_ceo(owner, org, company.id, idea.id)
        assert ceo.agent.type == "ceo"
        assert ceo.agent.configuration["ceo_initialized"] is True
        assert "Evidence policy" in ceo.system_instructions
        assert "no spending" in ceo.system_instructions.lower()
        assert ceo.goal_count == len(outcome.goals)

        # 7. Initial plan materialized against a real seeded goal.
        plan = await env["ceo_service"].generate_initial_plan(owner, org, company.id, idea.id)
        seeded_goal_ids = {goal.id for goal in outcome.goals}
        assert plan.goal_id in seeded_goal_ids
        assert plan.task_ids
        tasks = [
            await env["task_service"].get_task(owner, org, company.id, task_id)
            for task_id in plan.task_ids
        ]
        assert all(task.goal_id == plan.goal_id for task in tasks)
        assert all(task.company_id == company.id for task in tasks)

        # 8. Agent assignment: a roster agent (not the CEO) is selected.
        worker = next(agent for agent in outcome.agents if agent.type != "ceo")
        await _allow_agent_execution(env, company.id)
        assigned = next(
            agent
            for agent in await env["agents_repo"].list_for_company(company.id)
            if agent.id == worker.id
        )
        assert assigned.is_selectable()

        # 9. Authorization through the permission engine.
        executable = tasks[0]
        await env["task_service"].update_task(
            owner,
            org,
            company.id,
            executable.id,
            input={"objective": "read the bootstrap evidence note"},
        )
        snapshot, agent = await env["authorization"].authorize_task(
            owner, org, company.id, executable.id, agent_id=worker.id
        )
        assert snapshot.id == executable.id and agent.id == worker.id

        # 10. Bounded execution through NativeAgentRuntime.
        task, execution, result = await env["orchestration"].execute_task(
            owner,
            org,
            company.id,
            executable.id,
            agent_id=worker.id,
            tool_permissions={"echo": "allow"},
            context={
                "agent_capability": "read_only_file_access",
                "company_context": company.mission,
                "agent_role": worker.type,
            },
        )
        assert result.runtime == "native"
        assert len(result.tool_calls) == 1 and result.tool_calls[0].ok

        # 11. The result is verified and persisted (not merely claimed).
        assert result.is_success(), result.error
        assert task.status is TaskStatus.COMPLETED
        assert execution.status.value == "completed"
        assert result.metadata["runtime_state"] == "completed"
        assert result.output.get("echo") == "bootstrap evidence"

        # 12. Durable events for this tenant only. Idea/blueprint events are
        # organization-scoped (no company exists yet); company events are
        # company-scoped.
        org_events = await env["store"].list_for_organization(org)
        org_event_types = {event.type for event in org_events}
        assert {
            "business_idea.submitted",
            "business_blueprint.generated",
        } <= org_event_types
        # Re-validation is idempotent: it emits nothing the second time.
        assert "business_blueprint.validated" not in org_event_types
        events = await env["store"].list_for_company(org, company.id)
        event_types = {event.type for event in events}
        assert {
            "company_bootstrap.completed",
            "ceo.initialized",
            "ceo.initial_plan_created",
            "orchestration.executed",
        } <= event_types
        rival_org_events = await env["store"].list_for_organization(env["rival_org"])
        assert rival_org_events == []

        # 13. The observation reflects the completed work.
        observation = await env["observer"].observe(org, company.id)
        assert observation.digest
        assert observation.tasks_total == len(tasks)
        assert observation.failed_tasks == []
        assert observation.ready_tasks == []

        # 14. Idempotent retries: same idea key and same bootstrap.
        repeat_idea = await env["idea_service"].submit_idea(
            owner,
            org,
            raw_idea=IDEA,
            target_market="independent music teachers",
            idempotency_key="e2e-idea-1",
        )
        assert repeat_idea.id == idea.id
        assert repeat_idea.created_by_this_call is False
        retry = await env["bootstrap_service"].bootstrap_company(owner, org, idea.id)
        assert retry.reused is True
        assert retry.company.id == company.id
        assert len(await env["companies"].list_for_organization(org)) == 1

        # 15. Cross-tenant access is denied.
        with pytest.raises(NotAMember):
            await env["idea_service"].get_idea(env["rival"], org, idea.id)
        with pytest.raises(BusinessIdeaNotFound):
            await env["idea_service"].get_idea(env["rival"], env["rival_org"], idea.id)

        # 16. No cross-company data leaks into the other tenant.
        rival_companies = await env["companies"].list_for_organization(env["rival_org"])
        assert rival_companies == []
        rival_events = await env["store"].list_for_company(env["rival_org"], company.id)
        assert rival_events == []
        rival_ideas = await env["ideas"].list_for_organization(env["rival_org"])
        assert rival_ideas == []

    async def test_duplicate_bootstrap_concurrency_is_idempotent(
        self, stack: Any, tmp_path: Any
    ) -> None:
        env = stack(_build_runtime([], tmp_path))
        idea = await env["idea_service"].submit_idea(env["owner"], env["org"], raw_idea=IDEA)
        await env["blueprint_service"].generate_blueprint(
            env["owner"], env["org"], idea.id, env["idea_service"], context={}
        )
        first = await env["bootstrap_service"].bootstrap_company(env["owner"], env["org"], idea.id)
        second = await env["bootstrap_service"].bootstrap_company(env["owner"], env["org"], idea.id)
        assert first.company.id == second.company.id
        assert second.reused is True
        companies = await env["companies"].list_for_organization(env["org"])
        assert len(companies) == 1


class TestTenantIsolationMatrix:
    """Forged ids and cross-tenant reads must fail closed at every boundary."""

    async def test_forged_ids_are_not_found_or_denied(self, stack: Any, tmp_path: Any) -> None:
        from polsia.core.shared.errors import CompanyNotFoundError, NotFoundError
        from polsia.core.shared.ids import BusinessIdeaId, CompanyId, TaskId

        env = stack(_build_runtime([], tmp_path))
        owner, org = env["owner"], env["org"]
        idea = await env["idea_service"].submit_idea(owner, org, raw_idea=IDEA)
        forged_org = Organization.create(
            name="Ghost Org", slug="ghost-org", owner_user_id=env["rival"].id
        ).id
        forged_idea = BusinessIdeaId.generate()
        forged_company = CompanyId.generate()

        # Forged idea id inside the real tenant -> 404-equivalent.
        with pytest.raises(BusinessIdeaNotFound):
            await env["idea_service"].get_idea(owner, org, forged_idea)
        # Real idea id, forged/unjoined organization -> membership denied.
        with pytest.raises(NotAMember):
            await env["idea_service"].get_idea(owner, forged_org, idea.id)
        # Forged company id -> not found (after the artifact gate passes).
        await env["blueprint_service"].generate_blueprint(
            owner, org, idea.id, env["idea_service"], context={}
        )
        with pytest.raises(CompanyNotFoundError):
            await env["ceo_service"].initialize_ceo(owner, org, forged_company, idea.id)
        # Forged task id -> not found.
        with pytest.raises(NotFoundError):
            await env["task_service"].get_task(owner, org, forged_company, TaskId.generate())

    async def test_cross_tenant_blueprint_is_invisible(self, stack: Any, tmp_path: Any) -> None:
        env = stack(_build_runtime([], tmp_path))
