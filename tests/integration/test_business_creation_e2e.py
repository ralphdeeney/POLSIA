    async def test_retry_after_interrupted_generation_succeeds(
        self, stack: Any, tmp_path: Any
    ) -> None:
        class FlakyGenerator:
            name = "flaky"

            def __init__(self) -> None:
                self.calls = 0
                self._delegate = DeterministicBlueprintGenerator()

            async def generate(self, idea: Any, *, context: Any = None) -> Any:
                self.calls += 1
                if self.calls == 1:
                    raise ProviderUnavailable("interrupted")
                return await self._delegate.generate(idea, context=context)

        flaky = FlakyGenerator()
        env = stack(_build_runtime([], tmp_path), flaky)
        idea = await env["idea_service"].submit_idea(env["owner"], env["org"], raw_idea=IDEA)
        with pytest.raises(ProviderUnavailable):
            await env["blueprint_service"].generate_blueprint(
                env["owner"], env["org"], idea.id, env["idea_service"], context={}
            )
        # Nothing was persisted by the failed attempt: retry on the same idea.
        idea = await env["blueprint_service"].generate_blueprint(
            env["owner"], env["org"], idea.id, env["idea_service"], context={}
        )
        assert idea.blueprint_status is BlueprintStatus.VALIDATED
        assert idea.blueprint_version == 1
