"""Phase 4 wave 3 end-to-end: business creation to one verified execution.

Positive flow (mandate §13, 16 numbered steps):

 1. authenticated owners + tenant-scoped organizations
 2. business idea submitted (raw text preserved, intake validated)
 3. blueprint generated by the deterministic port
 4. blueprint verified as an artifact (schema/sections/consistency/ownership)
 5. company bootstrapped from the validated blueprint
 6. CEO agent configured from trusted company state
 7. initial plan generated and materialized against real goals
 8. agent assignment selected from the company roster
 9. execution authorized through the permission engine
10. bounded NativeAgentRuntime execution (one authorized tool call)
11. result verified (not merely claimed) and persisted
12. durable events recorded for this company only
13. company observation reflects the completed work
14. idempotent retries never duplicate the company/idea
15. cross-tenant reads and actions are denied
16. no cross-company data leaks into the other tenant

Negative cases in the same file use the same real services + persistence:
model provider outage, budget exhaustion, partial bootstrap failure with
rollback/retry, unauthorized execution, forged completion, prompt injection.
"""

